"""Generate a small After Effects ExtendScript project from an edit manifest."""

import math
import os


_ASPECT_SIZES = {
    "9:16": (1080, 1920),
    "16:9": (1920, 1080),
    "1:1": (1080, 1080),
    "4:5": (1080, 1350),
}


def _js_string(value):
    """Return a safely quoted JavaScript string literal, including Unicode escapes."""
    text = str(value)
    escaped = []
    for char in text:
        code = ord(char)
        if char == '"':
            escaped.append('\\"')
        elif char == "\\":
            escaped.append("\\\\")
        elif char == "\n":
            escaped.append("\\n")
        elif char == "\r":
            escaped.append("\\r")
        elif char == "\t":
            escaped.append("\\t")
        elif code < 0x20 or code > 0x7E:
            if code <= 0xFFFF:
                escaped.append("\\u%04x" % code)
            else:
                code -= 0x10000
                escaped.append("\\u%04x\\u%04x" % (0xD800 + (code >> 10), 0xDC00 + (code & 0x3FF)))
        else:
            escaped.append(char)
    return '"' + "".join(escaped) + '"'


def _number(value, label):
    try:
        number = float(value)
    except (TypeError, ValueError):
        raise ValueError("%s must be a finite number" % label)
    if not math.isfinite(number):
        raise ValueError("%s must be a finite number" % label)
    return str(int(number)) if number.is_integer() else repr(number)


def build_ae_script(project_name, aspect, fps, clips, captions, media_base_dir):
    """Build an ExtendScript file that imports media and creates a timed comp."""
    if not clips:
        raise ValueError("at least one clip is required")
    if not captions:
        raise ValueError("at least one caption is required")
    if aspect not in _ASPECT_SIZES:
        raise ValueError("unsupported aspect ratio: %s" % aspect)
    width, height = _ASPECT_SIZES[aspect]
    fps_value = _number(fps, "fps")
    if float(fps_value) <= 0:
        raise ValueError("fps must be positive")

    lines = [
        "// Generated by AI Studio. Run with File > Scripts > Run Script File.",
        "(function () {",
        "    app.beginUndoGroup(%s);" % _js_string("AI Studio: " + str(project_name)),
        "    var project = app.project || app.newProject();",
        "    var comp = project.items.addComp(%s, %d, %d, 1, 1, %s);" % (
            _js_string(str(project_name)), width, height, fps_value,
        ),
    ]
    max_end = 0.0
    media_base_dir = os.path.abspath(os.path.expanduser(str(media_base_dir)))
    for index, clip in enumerate(clips):
        try:
            src = clip["src"]
            source_in = float(clip["in"])
            source_out = float(clip["out"])
            start = float(clip["start"])
        except (KeyError, TypeError, ValueError):
            raise ValueError("each clip needs src, in, out, and start values")
        if not all(math.isfinite(v) for v in (source_in, source_out, start)) or source_out <= source_in or start < 0:
            raise ValueError("clip timing must be finite, with out > in and start >= 0")
        path = str(src) if os.path.isabs(str(src)) else os.path.join(media_base_dir, str(src))
        path = os.path.abspath(os.path.expanduser(path))
        end = start + (source_out - source_in)
        max_end = max(max_end, end)
        lines.extend([
            "    var footage%d = project.importFile(new ImportOptions(File(%s)));" % (index + 1, _js_string(path)),
            "    var layer%d = comp.layers.add(footage%d);" % (index + 1, index + 1),
            "    layer%d.startTime = %s;" % (index + 1, _number(start - source_in, "clip startTime")),
            "    layer%d.inPoint = %s;" % (index + 1, _number(start, "clip inPoint")),
            "    layer%d.outPoint = %s;" % (index + 1, _number(end, "clip outPoint")),
        ])
    for index, caption in enumerate(captions):
        try:
            caption_text = caption["text"]
            start = float(caption["start"])
            end = float(caption["end"])
        except (KeyError, TypeError, ValueError):
            raise ValueError("each caption needs text, start, and end values")
        if not math.isfinite(start) or not math.isfinite(end) or start < 0 or end <= start:
            raise ValueError("caption timing must be finite, with end > start >= 0")
        max_end = max(max_end, end)
        lines.extend([
            "    var caption%d = comp.layers.addText(%s);" % (index + 1, _js_string(caption_text)),
            "    caption%d.startTime = %s;" % (index + 1, _number(start, "caption start")),
            "    caption%d.inPoint = %s;" % (index + 1, _number(start, "caption start")),
            "    caption%d.outPoint = %s;" % (index + 1, _number(end, "caption end")),
        ])
    lines.extend([
        "    comp.duration = %s;" % _number(max_end, "comp duration"),
        "    app.endUndoGroup();",
        "}());",
        "",
    ])
    return "\n".join(lines)
